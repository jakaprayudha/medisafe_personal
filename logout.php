<?php

/**
 * =========================================================
 * LOGOUT.PHP
 * Medisafe - Clinic Management System
 * =========================================================
 */

session_start();

/*
|--------------------------------------------------------------------------
| Hapus seluruh data session
|--------------------------------------------------------------------------
*/

$_SESSION = [];


/*
|--------------------------------------------------------------------------
| Hapus cookie session
|--------------------------------------------------------------------------
| Jika session menggunakan cookie PHPSESSID,
| cookie tersebut juga dihapus dari browser.
|--------------------------------------------------------------------------
*/

if (ini_get('session.use_cookies')) {

   $params = session_get_cookie_params();

   setcookie(
      session_name(),
      '',
      time() - 42000,
      $params['path'],
      $params['domain'],
      $params['secure'],
      $params['httponly']
   );
}


/*
|--------------------------------------------------------------------------
| Destroy session
|--------------------------------------------------------------------------
*/

session_destroy();


/*
|--------------------------------------------------------------------------
| Redirect ke Login
|--------------------------------------------------------------------------
*/

header('Location: /medisafe_personal/index');

exit;
